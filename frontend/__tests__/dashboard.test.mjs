/**
 * Automated Frontend Verification Tests (Node built-in test runner: `node --test`)
 * Owner: Shreyash (Frontend & UI Testing)
 *
 * Verifies API client error handling, upload validation rules, mock-mode banner presence,
 * and report/trace rendering contracts without requiring a browser daemon.
 */

import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const FRONTEND_ROOT = path.resolve(__dirname, '..');

test('Frontend modular components and central API client exist', () => {
  const requiredFiles = [
    'types/radiology.ts',
    'lib/api.ts',
    'components/SystemStatusBar.tsx',
    'components/UploadPanel.tsx',
    'components/ImageViewer.tsx',
    'components/PredictionPanel.tsx',
    'components/ReportPanel.tsx',
    'components/AgentTracePanel.tsx',
    'app/page.tsx',
  ];

  for (const relPath of requiredFiles) {
    const fullPath = path.join(FRONTEND_ROOT, relPath);
    assert.equal(fs.existsSync(fullPath), true, `Expected ${relPath} to exist`);
  }
});

test('UploadPanel enforces PNG/JPEG validation and loading state', () => {
  const source = fs.readFileSync(
    path.join(FRONTEND_ROOT, 'components/UploadPanel.tsx'),
    'utf-8'
  );
  assert.match(source, /ACCEPTED_MIME_TYPES\s*=\s*\['image\/png',\s*'image\/jpeg'/);
  assert.match(source, /Validating & Uploading Scan\.\.\./);
  assert.match(source, /Running Vision & Agentic RAG Pipeline\.\.\./);
  assert.match(source, /role="alert"/);
});

test('ReportPanel displays explicit DEMO MODE notice and evidence citations', () => {
  const source = fs.readFileSync(
    path.join(FRONTEND_ROOT, 'components/ReportPanel.tsx'),
    'utf-8'
  );
  assert.match(
    source,
    /DEMO MODE: Results are simulated and are not generated by a trained medical\s+model\./
  );
  assert.match(source, /report\.evidence\.map/);
  assert.match(source, /ev\.document_title/);
  assert.match(source, /ev\.passage/);
});

test('PredictionPanel uses careful uncalibrated score terminology', () => {
  const source = fs.readFileSync(
    path.join(FRONTEND_ROOT, 'components/PredictionPanel.tsx'),
    'utf-8'
  );
  assert.match(source, /uncalibrated model output/);
  assert.equal(source.includes('AI Diagnostic Confidence'), false);
});

test('AgentTracePanel dynamically renders backend trace stages instead of static checkmarks', () => {
  const source = fs.readFileSync(
    path.join(FRONTEND_ROOT, 'components/AgentTracePanel.tsx'),
    'utf-8'
  );
  assert.match(source, /trace\.map\(\(step,\s*index\)/);
  assert.match(source, /Simulated Execution Trace \(Mock Mode\)/);
});

test('Central API client surfaces HTTP errors instead of silently returning fake data', () => {
  const pageSource = fs.readFileSync(
    path.join(FRONTEND_ROOT, 'app/page.tsx'),
    'utf-8'
  );
  const apiSource = fs.readFileSync(
    path.join(FRONTEND_ROOT, 'lib/api.ts'),
    'utf-8'
  );
  assert.match(apiSource, /export class ApiError extends Error/);
  assert.match(apiSource, /NEXT_PUBLIC_API_BASE_URL/);
  assert.equal(pageSource.includes('mock_fallback'), false);
});
