'use client';

import React from 'react';
import { ReportResponse } from '@/types/radiology';

interface ReportPanelProps {
  report: ReportResponse | null;
  loading: boolean;
}

export function ReportPanel({ report, loading }: ReportPanelProps) {
  return (
    <div className="bg-white border border-slate-200 rounded-md p-4 shadow-sm h-full flex flex-col">
      <div className="flex items-center justify-between border-b border-slate-100 pb-2 mb-4">
        <h2 className="text-sm font-semibold text-slate-900">Report</h2>
        {report && (
          <span className="text-xs font-mono text-slate-500">
            Evidence: {report.evidence_status}
          </span>
        )}
      </div>

      {loading ? (
        <div className="flex-1 flex flex-col justify-center space-y-3 py-8 animate-pulse">
          <div className="h-4 bg-slate-200 rounded w-1/3" />
          <div className="h-20 bg-slate-100 rounded" />
          <div className="h-4 bg-slate-200 rounded w-1/4" />
          <div className="h-36 bg-slate-100 rounded" />
          <div className="h-28 bg-slate-100 rounded" />
        </div>
      ) : !report ? (
        <div className="flex-1 flex items-center justify-center py-12 text-center text-xs text-slate-400 bg-slate-50/60 border border-dashed border-slate-200 rounded">
          Click Analyze Chest X-Ray to generate the report.
        </div>
      ) : (
        <div className="flex-1 flex flex-col justify-between space-y-4 text-xs">
          <div className="space-y-4">
            {report.mode === 'mock' && (
              <div
                role="status"
                className="bg-amber-50 border border-amber-300 text-amber-950 p-2.5 rounded text-xs"
              >
                DEMO MODE: Results are simulated and are not generated by a trained medical
                model.
              </div>
            )}

            <div className="space-y-1.5">
              <h3 className="text-xs font-semibold text-slate-600">Impression</h3>
              <div className="bg-slate-50 border border-slate-200 p-3 rounded text-slate-900 leading-relaxed">
                {report.impression}
              </div>
            </div>

            <div className="space-y-1.5">
              <h3 className="text-xs font-semibold text-slate-600">Findings</h3>
              <ul className="space-y-2 bg-slate-50 border border-slate-200 p-3 rounded text-slate-800">
                {report.findings.map((finding, idx) => (
                  <li key={idx} className="leading-relaxed">
                    - {finding}
                  </li>
                ))}
              </ul>
            </div>
          </div>

          {report.evidence.length > 0 && (
            <div className="space-y-2 pt-1">
              <h3 className="text-xs font-semibold text-slate-600">
                Citations ({report.evidence.length})
              </h3>
              <div className="grid grid-cols-1 gap-2">
                {report.evidence.map((ev) => (
                  <div
                    key={ev.evidence_id}
                    className="border border-slate-200 rounded p-2.5 bg-slate-50/50 space-y-1"
                  >
                    <div className="flex items-center justify-between gap-2">
                      <span className="font-semibold text-slate-900">
                        {ev.document_title}
                      </span>
                      <span className="font-mono text-slate-500 flex-shrink-0">
                        {ev.chunk_id} ({ev.relevance_score.toFixed(2)})
                      </span>
                    </div>
                    <p className="text-slate-700 leading-relaxed">{ev.passage}</p>
                  </div>
                ))}
              </div>
            </div>
          )}
        </div>
      )}
    </div>
  );
}
